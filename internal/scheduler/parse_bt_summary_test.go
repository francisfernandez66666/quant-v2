package scheduler

import (
	"strings"
	"testing"
)

func TestParseBtSummaryLabeled(t *testing.T) {
	out := "回测进度 30%\n" +
		"==============================================\n" +
		"战法历史回测: DoubleBump（300 只股票）\n" +
		"----------------------------------------------\n" +
		"触发信号数: 270\n胜率: 47.78% (129 胜 / 141 负)\n平均盈利: +7.85%\n" +
		"平均亏损: -5.45%\n盈亏比: 1.31\n平均持仓天数: 1.0\n" +
		"==============================================\n" +
		"战法历史回测: 因子战法#1（300 只股票）\n----------------------------------------------\n" +
		"触发信号数: 12897\n胜率: 45.29% (5841 胜 / 7056 负)\n盈亏比: 1.19\n平均持仓天数: 9.1\n" +
		"==============================================\n" +
		"战法历史回测: N形（300 只股票）\n----------------------------------------------\n无触发信号。\n"
	got := parseBtSummary(out)
	want1 := "【双响炮】胜率 47.78% 盈亏比 1.31 触发 270 持仓 1.0天"
	want2 := "【因子战法#1】胜率 45.29% 盈亏比 1.19 触发 12897 持仓 9.1天"
	want3 := "【N形】无触发信号"
	lines := strings.Split(got, "\n")
	if len(lines) != 3 || lines[0] != want1 || lines[1] != want2 || lines[2] != want3 {
		t.Fatalf("got:\n%s", got)
	}
	if parseBtSummary("没有任何报告") != "无触发信号" {
		t.Fatal("empty fallback")
	}
}
